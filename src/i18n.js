const baseTranslations = Object.entries(translations).filter(([key])=>key.length>=3).sort((a,b)=>b[0].length-a[0].length);
const localizeString = value => {
  const leading=value.match(/^\s*/)[0], trailing=value.match(/\s*$/)[0];
  const source=value.trim();
  if(!source)return value;
  if(Object.prototype.hasOwnProperty.call(translations,source))return leading+translations[source]+trailing;
  for(const [pattern, format] of patterns){
    const m=source.match(pattern);
    if(m)return leading+format(...m)+trailing;
  }
  // For combined JSX text fragments, replace only known UI phrases.
  // Never rewrite data in storage, form values, URLs, or API payloads.
  let result=source;
  for(const [zh,en] of baseTranslations){
    if(result.includes(zh))result=result.split(zh).join(en);
  }
  if(result!==source){
    result=result.replace(/，/g,", ").replace(/。/g,".").replace(/；/g,"; ").replace(/（/g," (").replace(/）/g,")");
    return leading+result+trailing;
  }
  return value;
};
export const tr = value => {
  if(!isEnglish() || typeof value!=="string")return value;
  return localizeString(value);
};
